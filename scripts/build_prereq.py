# ============ 校验 & 构建 ============
miss = []
good = []
for a, b, t in E:
    if a not in NAME_SET or b not in NAME_SET:
        miss.append((a, b, t))
    else:
        good.append((a, b, t))
if miss:
    print('==== 名字未命中(需修正) ====')
    for a, b, t in miss:
        for x in (a, b):
            if x not in NAME_SET:
                sug = difflib.get_close_matches(x, NAMES, 1, 0.6)
                print(f'  未命中: {x!r}  ->  建议: {sug}')
    print(f'共 {len(miss)} 条边未通过,已跳过。')

# 建邻接
A = np.zeros((N, N), dtype=np.int8)
for a, b, t in good:
    A[n2i[a], n2i[b]] = 1

# DAG 校验(拓扑排序 / Kahn)
indeg = A.sum(axis=0).copy()
queue = [i for i in range(N) if indeg[i] == 0]
seen = 0
while queue:
    i = queue.pop(); seen += 1
    for j in range(N):
        if A[i, j]:
            indeg[j] -= 1
            if indeg[j] == 0: queue.append(j)
cycles = (N - seen)  # 留在图里没出队的点数
print(f'\n==== 构建 ====')
print(f'有效边数: {len(good)} | 端点非法已跳过: {len(miss)}')
print(f'DAG 校验: {("通过(无环)" if cycles==0 else f"有环,涉及{cycles}个节点")}')
if cycles:
    resid = [NAMES[i] for i in range(N) if indeg[i] > 0]
    print('  残留节点(在环或环下游):', resid)

